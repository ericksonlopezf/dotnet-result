using System;
using System.Collections.Generic;
using System.Diagnostics.CodeAnalysis;
using System.Diagnostics.Contracts;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using EricksonLopez.Result;

namespace EricksonLopez.Result.Maybe;

/// <summary>
/// Represents an optional value of type <typeparamref name="T"/> with zero heap allocation.
/// </summary>
/// <typeparam name="T">The underlying value type.</typeparam>
[StructLayout(LayoutKind.Auto)]
public readonly struct Maybe<T> : IEquatable<Maybe<T>>
{
    private readonly bool _hasValue;
    private readonly T _value;

    /// <summary>
    /// Gets a value indicating whether this instance contains a value.
    /// </summary>
    public bool HasValue => _hasValue;

    /// <summary>
    /// Gets a value indicating whether this instance does not contain a value.
    /// </summary>
    public bool HasNoValue => !_hasValue;

    /// <summary>
    /// Gets the underlying value if present; otherwise throws an <see cref="InvalidOperationException"/>.
    /// </summary>
    /// <exception cref="InvalidOperationException">Thrown when <see cref="HasValue"/> is false.</exception>
    public T Value
    {
        get
        {
            if (!_hasValue)
                throw new InvalidOperationException("Cannot access Value when Maybe has no value.");
            return _value!;
        }
    }

    /// <summary>
    /// Represents an empty <see cref="Maybe{T}"/> with no value.
    /// </summary>
    public static Maybe<T> None => default;

    /// <summary>
    /// Creates a <see cref="Maybe{T}"/> containing the specified value, or <see cref="None"/> if null.
    /// </summary>
    /// <param name="value">The optional value to wrap.</param>
    /// <returns>A <see cref="Maybe{T}"/> containing <paramref name="value"/> if not <see langword="null"/>; otherwise <see cref="None"/>.</returns>
    [Pure]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static Maybe<T> From(T? value)
    {
        if (value is null)
            return None;

        return new Maybe<T>(value);
    }

    private Maybe(T value)
    {
        _hasValue = true;
        _value = value;
    }

    /// <summary>
    /// Attempts to retrieve the value. Returns true if present, otherwise false.
    /// </summary>
    /// <param name="value">When this method returns, contains the underlying value if present; otherwise, the default value.</param>
    /// <returns><see langword="true"/> if this instance contains a value; otherwise, <see langword="false"/>.</returns>
    [Pure]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public bool TryGetValue([MaybeNullWhen(false)] out T value)
    {
        value = _value;
        return _hasValue;
    }

    /// <summary>
    /// Returns the underlying value if present; otherwise returns <paramref name="defaultValue"/>.
    /// </summary>
    /// <param name="defaultValue">The fallback value to return if no value is present.</param>
    /// <returns>The underlying value if present; otherwise, <paramref name="defaultValue"/>.</returns>
    [Pure]
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public T GetValueOrDefault(T defaultValue)
        => _hasValue ? _value! : defaultValue;

    /// <summary>
    /// Returns the underlying value if present; otherwise invokes <paramref name="fallback"/>.
    /// </summary>
    /// <param name="fallback">The function generating a fallback value if no value is present.</param>
    /// <returns>The underlying value if present; otherwise, the value generated by <paramref name="fallback"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="fallback"/> is <see langword="null"/></exception>
    [Pure]
    public T GetValueOrFallback(Func<T> fallback)
    {
        ArgumentNullException.ThrowIfNull(fallback);
        return _hasValue ? _value! : fallback();
    }

    /// <summary>
    /// Maps the value using <paramref name="mapper"/> if present; otherwise returns <see cref="Maybe{TNext}.None"/>.
    /// </summary>
    /// <typeparam name="TNext">The return type of the mapper function.</typeparam>
    /// <param name="mapper">The projection function applied to the value.</param>
    /// <returns>A new <see cref="Maybe{TNext}"/> containing the mapped value if present; otherwise, <see cref="Maybe{TNext}.None"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="mapper"/> is <see langword="null"/></exception>
    [Pure]
    public Maybe<TNext> Map<TNext>(Func<T, TNext> mapper)
    {
        ArgumentNullException.ThrowIfNull(mapper);
        return _hasValue ? Maybe<TNext>.From(mapper(_value!)) : Maybe<TNext>.None;
    }

    /// <summary>
    /// Maps the value with closure-free <paramref name="state"/> if present.
    /// </summary>
    /// <typeparam name="TState">The type of the state object passed to the mapper.</typeparam>
    /// <typeparam name="TNext">The return type of the mapper function.</typeparam>
    /// <param name="state">The state value passed to the mapper function.</param>
    /// <param name="mapper">The projection function applied to state and the value.</param>
    /// <returns>A new <see cref="Maybe{TNext}"/> containing the mapped value if present; otherwise, <see cref="Maybe{TNext}.None"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="mapper"/> is <see langword="null"/></exception>
    [Pure]
    public Maybe<TNext> Map<TState, TNext>(TState state, Func<TState, T, TNext> mapper)
    {
        ArgumentNullException.ThrowIfNull(mapper);
        return _hasValue ? Maybe<TNext>.From(mapper(state, _value!)) : Maybe<TNext>.None;
    }

    /// <summary>
    /// Binds to another <see cref="Maybe{TNext}"/> if present; otherwise returns <see cref="Maybe{TNext}.None"/>.
    /// </summary>
    /// <typeparam name="TNext">The value type of the chained maybe.</typeparam>
    /// <param name="bind">The operation to execute with the value if present.</param>
    /// <returns>The result of executing <paramref name="bind"/> if present; otherwise, <see cref="Maybe{TNext}.None"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="bind"/> is <see langword="null"/></exception>
    [Pure]
    public Maybe<TNext> Bind<TNext>(Func<T, Maybe<TNext>> bind)
    {
        ArgumentNullException.ThrowIfNull(bind);
        return _hasValue ? bind(_value!) : Maybe<TNext>.None;
    }

    /// <summary>
    /// Binds to another <see cref="Maybe{TNext}"/> with closure-free <paramref name="state"/>.
    /// </summary>
    /// <typeparam name="TState">The type of the state object passed to the bind function.</typeparam>
    /// <typeparam name="TNext">The value type of the chained maybe.</typeparam>
    /// <param name="state">The state value passed to the bind function.</param>
    /// <param name="bind">The operation to execute with state and the value if present.</param>
    /// <returns>The result of executing <paramref name="bind"/> if present; otherwise, <see cref="Maybe{TNext}.None"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="bind"/> is <see langword="null"/></exception>
    [Pure]
    public Maybe<TNext> Bind<TState, TNext>(TState state, Func<TState, T, Maybe<TNext>> bind)
    {
        ArgumentNullException.ThrowIfNull(bind);
        return _hasValue ? bind(state, _value!) : Maybe<TNext>.None;
    }

    /// <summary>
    /// Matches either branch depending on whether this instance has a value.
    /// </summary>
    /// <typeparam name="TOut">The output type produced by the matching functions.</typeparam>
    /// <param name="onValue">The function to evaluate with the value if present.</param>
    /// <param name="onNone">The function to evaluate if no value is present.</param>
    /// <returns>The value produced by either <paramref name="onValue"/> or <paramref name="onNone"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="onValue"/> or <paramref name="onNone"/> is <see langword="null"/></exception>
    [Pure]
    public TOut Match<TOut>(Func<T, TOut> onValue, Func<TOut> onNone)
    {
        ArgumentNullException.ThrowIfNull(onValue);
        ArgumentNullException.ThrowIfNull(onNone);
        return _hasValue ? onValue(_value!) : onNone();
    }

    /// <summary>
    /// Filters the value against <paramref name="predicate"/>; returns <see cref="None"/> if the predicate fails.
    /// </summary>
    /// <param name="predicate">The condition to test on the underlying value.</param>
    /// <returns>This instance if the condition is met; otherwise, <see cref="None"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="predicate"/> is <see langword="null"/></exception>
    [Pure]
    public Maybe<T> Ensure(Func<T, bool> predicate)
    {
        ArgumentNullException.ThrowIfNull(predicate);
        if (!_hasValue || !predicate(_value!))
            return None;
        return this;
    }

    /// <summary>
    /// Converts this <see cref="Maybe{T}"/> to a <see cref="Result{T}"/>, using <paramref name="notFoundError"/> if empty.
    /// </summary>
    /// <param name="notFoundError">The error to return if no value is present.</param>
    /// <returns>A successful <see cref="Result{T}"/> containing the value if present; otherwise, a failure with <paramref name="notFoundError"/>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="notFoundError"/> is <see langword="null"/></exception>
    [Pure]
    public Result<T> ToResult(Error notFoundError)
    {
        ArgumentNullException.ThrowIfNull(notFoundError);
        return _hasValue ? Result.Success(_value!) : Result.Failure<T>(notFoundError);
    }

    /// <summary>
    /// Converts this <see cref="Maybe{T}"/> to a <see cref="Result{T}"/>, using <paramref name="errorFactory"/> if empty.
    /// </summary>
    /// <param name="errorFactory">A factory that generates the error if no value is present.</param>
    /// <returns>A successful <see cref="Result{T}"/> containing the value if present; otherwise, a failure with the generated error.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="errorFactory"/> is <see langword="null"/></exception>
    [Pure]
    public Result<T> ToResult(Func<Error> errorFactory)
    {
        ArgumentNullException.ThrowIfNull(errorFactory);
        return _hasValue ? Result.Success(_value!) : Result.Failure<T>(errorFactory());
    }

    /// <summary>Converts a nullable value implicitly into a <see cref="Maybe{T}"/>.</summary>
    /// <param name="value">The value to wrap.</param>
    public static implicit operator Maybe<T>(T? value) => From(value);

    /// <summary>Determines whether this instance is equal to another <see cref="Maybe{T}"/>.</summary>
    /// <param name="other">The other instance to compare against.</param>
    /// <returns><see langword="true"/> if both instances represent the same value; otherwise, <see langword="false"/>.</returns>
    public bool Equals(Maybe<T> other)
    {
        if (_hasValue != other._hasValue) return false;
        if (!_hasValue) return true;
        return EqualityComparer<T>.Default.Equals(_value!, other._value!);
    }

    /// <inheritdoc/>
    public override bool Equals(object? obj) => obj is Maybe<T> other && Equals(other);

    /// <inheritdoc/>
    public override int GetHashCode() => _hasValue ? HashCode.Combine(true, EqualityComparer<T>.Default.GetHashCode(_value!)) : 0;

    /// <summary>Determines whether two <see cref="Maybe{T}"/> instances are equal.</summary>
    /// <param name="left">The first instance to compare.</param>
    /// <param name="right">The second instance to compare.</param>
    /// <returns><see langword="true"/> if both instances are equal; otherwise, <see langword="false"/>.</returns>
    public static bool operator ==(Maybe<T> left, Maybe<T> right) => left.Equals(right);

    /// <summary>Determines whether two <see cref="Maybe{T}"/> instances are not equal.</summary>
    /// <param name="left">The first instance to compare.</param>
    /// <param name="right">The second instance to compare.</param>
    /// <returns><see langword="true"/> if the instances are not equal; otherwise, <see langword="false"/>.</returns>
    public static bool operator !=(Maybe<T> left, Maybe<T> right) => !left.Equals(right);

    /// <inheritdoc/>
    public override string ToString() => _hasValue ? $"Some({_value})" : "None";
}

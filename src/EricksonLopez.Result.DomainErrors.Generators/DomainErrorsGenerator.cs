using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace EricksonLopez.Result.DomainErrors.Generators;

/// <summary>
/// Represents an incremental source generator producing strongly-typed domain error factory classes
/// from <c>*.errors.json</c> additional file declarations.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DomainErrorsGenerator : IIncrementalGenerator
{
    // Stryker disable all : Roslyn generator metadata
    private static readonly string GeneratorVersion =
        typeof(DomainErrorsGenerator).Assembly.GetName().Version?.ToString() ?? "3.0.0.0";
    // Stryker restore all

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var errorFiles = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".errors.json", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, cancellationToken) =>
            {
                var text = file.GetText(cancellationToken);
                if (text is null)
                {
                    return null;
                }

                return DomainErrorJsonParser.TryParse(text.ToString());
            })
            .Where(static model => model is not null);

        context.RegisterSourceOutput(errorFiles, static (productionContext, model) =>
        {
            if (model is null)
            {
                return;
            }

            string source = GenerateSource(model);
            productionContext.AddSource($"{model.ClassName}.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    // Stryker disable String : Generator template strings
    private static string GenerateSource(DomainErrorClassModel model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {model.NamespaceName};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Strongly-typed domain error factory methods for <c>{model.ClassName}</c>.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"EricksonLopez.Result.DomainErrors.Generators\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"public static partial class {model.ClassName}");
        sb.AppendLine("{");

        foreach (var error in model.Errors)
        {
            GenerateErrorFactoryMethod(sb, error);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void GenerateErrorFactoryMethod(StringBuilder sb, DomainErrorModel error)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine($"    /// Creates a domain <see cref=\"global::EricksonLopez.Result.Error\"/> for <c>{error.Code}</c>.");
        sb.AppendLine("    /// </summary>");

        var paramList = new StringBuilder();
        var formatArgs = new StringBuilder();

        for (int i = 0; i < error.Parameters.Length; i++)
        {
            if (i > 0)
            {
                paramList.Append(", ");
                formatArgs.Append(", ");
            }

            var p = error.Parameters[i];
            paramList.Append($"{p.Type} {p.Name}");
            formatArgs.Append(p.Name);
        }

        sb.AppendLine($"    public static global::EricksonLopez.Result.Error {error.Name}({paramList})");
        sb.AppendLine("    {");

        string descExpr;
        if (error.Parameters.Length == 0)
        {
            descExpr = $"\"{EscapeString(error.Description)}\"";
        }
        else
        {
            descExpr = $"global::System.String.Format(global::System.Globalization.CultureInfo.InvariantCulture, \"{EscapeString(error.Description)}\", {formatArgs})";
        }

        string typeName = MapType(error.Type);
        sb.AppendLine($"        var builder = global::EricksonLopez.Result.Error.Create(\"{EscapeString(error.Code)}\", {descExpr})");
        sb.AppendLine($"            .WithType(global::EricksonLopez.Result.ErrorType.{typeName});");

        if (!string.IsNullOrWhiteSpace(error.Severity))
        {
            sb.AppendLine($"        builder = builder.WithSeverity(global::EricksonLopez.Result.ErrorSeverity.{error.Severity});");
        }

        if (!string.IsNullOrWhiteSpace(error.Retryability))
        {
            sb.AppendLine($"        builder = builder.WithRetryability(global::EricksonLopez.Result.ErrorRetryability.{error.Retryability});");
        }

        if (!string.IsNullOrWhiteSpace(error.DescriptionKey))
        {
            sb.AppendLine($"        builder = builder.WithDescriptionKey(\"{EscapeString(error.DescriptionKey!)}\");");
        }

        sb.AppendLine("        return builder.Build();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }
    // Stryker restore String

    private static string MapType(string type)
    {
        return type.ToLowerInvariant() switch
        {
            "validation" => "Validation",
            "notfound" => "NotFound",
            "conflict" => "Conflict",
            "unauthorized" => "Unauthorized",
            "forbidden" => "Forbidden",
            "unavailable" => "Unavailable",
            "unexpected" => "Unexpected",
            _ => "Failure"
        };
    }

    private static string EscapeString(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");
    }
}
